INSERT INTO districts (name, department, province, latitude, longitude)
SELECT c.nombre_visible, c.departamento, c.provincia, c.latitud, c.longitud
FROM catalogo_distritos AS c
WHERE NOT EXISTS (
  SELECT 1
  FROM districts AS d
  WHERE lower(trim(d.department)) = lower(c.departamento)
    AND (
      lower(trim(d.name)) = lower(c.nombre_visible)
      OR (
        lower(trim(d.name)) = lower(c.nombre)
        AND lower(trim(d.province)) = lower(c.provincia)
      )
    )
)
ORDER BY c.ubigeo
ON CONFLICT (name, department) DO NOTHING;

COMMIT;
